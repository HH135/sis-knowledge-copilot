-- Procedure: dbo.USP_CREATE_ESTIMATE
-- Description: 정비 주문에 대한 견적을 작성한다
-- Tables: TB_REPAIR_ORDER, TB_ESTIMATE
CREATE PROCEDURE dbo.USP_CREATE_ESTIMATE
    @ESTIMATE_NO varchar(20),
    @ORDER_NO varchar(20),
    @LABOR_AMOUNT decimal(14,2),
    @PART_AMOUNT decimal(14,2)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (
        SELECT 1 FROM dbo.TB_REPAIR_ORDER
        WHERE ORDER_NO = @ORDER_NO AND CLOSED_AT IS NULL
    )
        THROW 50008, 'Open repair order was not found.', 1;

    INSERT INTO dbo.TB_ESTIMATE
        (ESTIMATE_NO, ORDER_NO, ESTIMATE_STATUS, LABOR_AMOUNT, PART_AMOUNT, TOTAL_AMOUNT, CREATED_AT)
    VALUES
        (@ESTIMATE_NO, @ORDER_NO, 'DRAFT', @LABOR_AMOUNT, @PART_AMOUNT,
         @LABOR_AMOUNT + @PART_AMOUNT, SYSUTCDATETIME());
END;
