-- Procedure: dbo.USP_CREATE_REPAIR_ORDER
-- Description: 확정 예약을 정비 주문으로 접수한다
-- Tables: TB_APPOINTMENT, TB_REPAIR_ORDER, TB_INTERFACE_LOG
CREATE PROCEDURE dbo.USP_CREATE_REPAIR_ORDER
    @ORDER_NO varchar(20),
    @APPT_NO varchar(20)
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO dbo.TB_REPAIR_ORDER
        (ORDER_NO, CUST_NO, VIN, APPT_NO, ORDER_STATUS, OPENED_AT, CLOSED_AT)
    SELECT @ORDER_NO, CUST_NO, VIN, APPT_NO, 'OPEN', SYSUTCDATETIME(), NULL
    FROM dbo.TB_APPOINTMENT
    WHERE APPT_NO = @APPT_NO
      AND APPT_STATUS = 'CONFIRMED';

    IF @@ROWCOUNT = 0
        THROW 50005, 'Confirmed appointment was not found.', 1;

    UPDATE dbo.TB_APPOINTMENT
    SET APPT_STATUS = 'CONVERTED'
    WHERE APPT_NO = @APPT_NO;

    EXEC dbo.USP_WRITE_INTERFACE_LOG
        @LOG_NO = 1001,
        @MESSAGE_TYPE = 'ORDER_CREATED',
        @CORRELATION_ID = @ORDER_NO,
        @PROCESS_STATUS = 'DONE',
        @PAYLOAD_SUMMARY = N'Repair order created';

    EXEC dbo.USP_LEGACY_SYNC @ORDER_NO = @ORDER_NO;

    -- EXEC dbo.USP_CONFIRM_APPOINTMENT @APPT_NO = @APPT_NO, @BAY_NO = 'BAY-01';
END;
