-- Procedure: dbo.USP_CREATE_PART_PURCHASE_ORDER
-- Description: 공급업체에 부품 구매 주문을 생성한다
-- Tables: TB_PART_PURCHASE_ORDER, TB_PART_PURCHASE_LINE, TB_SUPPLIER, TB_PART
CREATE PROCEDURE dbo.USP_CREATE_PART_PURCHASE_ORDER
    @PO_NO varchar(20),
    @SUPPLIER_NO varchar(20),
    @BRANCH_NO varchar(12),
    @PART_NO varchar(24),
    @ORDER_QTY decimal(12,2),
    @UNIT_PRICE decimal(12,2),
    @EXPECTED_AT date
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NOT EXISTS (SELECT 1 FROM dbo.TB_SUPPLIER WHERE SUPPLIER_NO = @SUPPLIER_NO AND ACTIVE_YN = 'Y')
        THROW 50017, 'Active supplier was not found.', 1;

    IF NOT EXISTS (SELECT 1 FROM dbo.TB_PART WHERE PART_NO = @PART_NO AND ACTIVE_YN = 'Y')
        THROW 50018, 'Active part was not found.', 1;

    BEGIN TRANSACTION;

    INSERT INTO dbo.TB_PART_PURCHASE_ORDER
        (PO_NO, SUPPLIER_NO, BRANCH_NO, PO_STATUS, ORDERED_AT, EXPECTED_AT, TOTAL_AMOUNT)
    VALUES
        (@PO_NO, @SUPPLIER_NO, @BRANCH_NO, 'OPEN', SYSUTCDATETIME(), @EXPECTED_AT, @ORDER_QTY * @UNIT_PRICE);

    INSERT INTO dbo.TB_PART_PURCHASE_LINE
        (PO_NO, LINE_NO, PART_NO, ORDER_QTY, UNIT_PRICE, RECEIVED_QTY)
    VALUES
        (@PO_NO, 1, @PART_NO, @ORDER_QTY, @UNIT_PRICE, 0);

    COMMIT TRANSACTION;

    EXEC dbo.USP_WRITE_INTERFACE_LOG
        @LOG_NO = 1005,
        @MESSAGE_TYPE = 'PARTS_ORDERED',
        @CORRELATION_ID = @PO_NO,
        @PROCESS_STATUS = 'DONE',
        @PAYLOAD_SUMMARY = N'Purchase order created';
END;
