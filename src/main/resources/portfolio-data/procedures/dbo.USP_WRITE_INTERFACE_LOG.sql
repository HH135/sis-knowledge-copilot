-- Procedure: dbo.USP_WRITE_INTERFACE_LOG
-- Description: 가상 연동 메시지 처리 결과를 기록한다
-- Tables: TB_INTERFACE_LOG
CREATE PROCEDURE dbo.USP_WRITE_INTERFACE_LOG
    @LOG_NO bigint,
    @MESSAGE_TYPE varchar(24),
    @CORRELATION_ID varchar(40),
    @PROCESS_STATUS varchar(16),
    @PAYLOAD_SUMMARY nvarchar(500) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO dbo.TB_INTERFACE_LOG
        (LOG_NO, MESSAGE_TYPE, CORRELATION_ID, PROCESS_STATUS, PAYLOAD_SUMMARY, CREATED_AT)
    VALUES
        (@LOG_NO, @MESSAGE_TYPE, @CORRELATION_ID, @PROCESS_STATUS, @PAYLOAD_SUMMARY, SYSUTCDATETIME());
END;
