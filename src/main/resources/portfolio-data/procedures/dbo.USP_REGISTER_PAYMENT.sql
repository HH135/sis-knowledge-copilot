-- Procedure: dbo.USP_REGISTER_PAYMENT
-- Description: 정비 주문의 결제 예정 내역을 등록한다
-- Tables: TB_PAYMENT, TB_REPAIR_ORDER
CREATE PROCEDURE dbo.USP_REGISTER_PAYMENT
    @PAYMENT_NO varchar(24),
    @ORDER_NO varchar(20),
    @PAYMENT_METHOD varchar(16),
    @PAYMENT_AMOUNT decimal(14,2)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM dbo.TB_REPAIR_ORDER WHERE ORDER_NO = @ORDER_NO)
        THROW 50011, 'Repair order was not found.', 1;

    INSERT INTO dbo.TB_PAYMENT
        (PAYMENT_NO, ORDER_NO, PAYMENT_METHOD, PAYMENT_AMOUNT, PAYMENT_STATUS, PAID_AT)
    VALUES
        (@PAYMENT_NO, @ORDER_NO, @PAYMENT_METHOD, @PAYMENT_AMOUNT, 'PENDING', NULL);
END;
